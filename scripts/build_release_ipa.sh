#!/usr/bin/env bash
# Builds an App Store-ready iOS release with the REAL AdMob ids.
#
# Mirrors scripts/build_release_aab.sh for iOS:
#   - the AdMob *app id* (ADMOB_APP_ID_IOS) is written into the gitignored
#     ios/Flutter/AdMob.secret.xcconfig, which overrides the test default and
#     feeds Info.plist's GADApplicationIdentifier via $(ADMOB_APP_ID_IOS);
#   - the iOS ad-unit ids are passed as --dart-define (ADMOB_*_IOS), which
#     AdsService reads on iOS.
# Any missing value falls back to Google's TEST ids. Android is untouched.
#
# Usage:  bash scripts/build_release_ipa.sh
set -euo pipefail
cd "$(dirname "$0")/.."

PROPS="android/admob.properties"
prop() { [ -f "$PROPS" ] && grep -E "^$1=" "$PROPS" | head -1 | cut -d= -f2- || true; }

APP_ID_IOS="$(prop ADMOB_APP_ID_IOS)"
REWARDED_IOS="$(prop ADMOB_REWARDED_IOS)"
INTERSTITIAL_IOS="$(prop ADMOB_INTERSTITIAL_IOS)"
BANNER_IOS="$(prop ADMOB_BANNER_IOS)"
TEST_DEVICES="$(prop ADMOB_TEST_DEVICE_IDS)"

SECRET="ios/Flutter/AdMob.secret.xcconfig"
if [[ -n "$APP_ID_IOS" ]]; then
  printf '// Generated by scripts/build_release_ipa.sh — do not commit.\nADMOB_APP_ID_IOS = %s\n' "$APP_ID_IOS" > "$SECRET"
  echo "Wrote real iOS AdMob app id to $SECRET"
else
  echo "WARNING: ADMOB_APP_ID_IOS missing in $PROPS — using the TEST app id." >&2
fi

flutter build ipa --release \
  --dart-define=ADMOB_REWARDED_IOS="$REWARDED_IOS" \
  --dart-define=ADMOB_INTERSTITIAL_IOS="$INTERSTITIAL_IOS" \
  --dart-define=ADMOB_BANNER_IOS="$BANNER_IOS" \
  --dart-define=ADMOB_TEST_DEVICE_IDS="$TEST_DEVICES"

echo
echo "Done → build/ios/ipa/*.ipa  (open ios/Runner.xcworkspace to archive/upload)"
